function applyMenuContent(lang) {
  const page = document.body.dataset.menuPage;
  if (!page) return;

  const t = MENU_PAGE_TRANSLATIONS[lang] || MENU_PAGE_TRANSLATIONS.es;
  const meta = document.querySelector('meta[name="description"]');
  if (page === "dinner") {
    document.title = t.dinnerPageTitle;
    if (meta) meta.content = t.dinnerPageDesc;
  } else if (page === "drinks") {
    document.title = t.drinksPageTitle;
    if (meta) meta.content = t.drinksPageDesc;
  } else if (page === "groups") {
    document.title = t.groupsPageTitle;
    if (meta) meta.content = t.groupsPageDesc;
  } else if (page === "cachoBurgers") {
    document.title = t.cbPageTitle;
    if (meta) meta.content = t.cbPageDesc;
  }

  if (typeof applyMenuFromSheet === "function") applyMenuFromSheet(lang);
}

function mergeMenuTranslations() {
  if (typeof translations === "undefined") return;
  ["es", "ca", "en"].forEach((lang) => {
    Object.assign(translations[lang], MENU_PAGE_TRANSLATIONS[lang]);
  });
}

